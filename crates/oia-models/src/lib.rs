//! `oia-models` — Provider-neutral AI execution interface, workspace data-handling policy guards,
//! untrusted document prompt-injection isolation, and structural citation anchor validation
//! (`DOC-03`–`DOC-05`, `D15`, `A03`, `docs/architecture.md` Section 6.3).

use std::fmt;

use oia_domain::{Document, OpaqueId, VersionId};

/// Execution locality of a model provider (`docs/architecture.md` Section 6.3).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ModelLocality {
    /// Local on-device inference (no external network transmission).
    Local,
    /// Remote provider endpoint (requires workspace policy authorization and user disclosure).
    Remote {
        /// Provider name.
        provider_name: String,
    },
}

/// Workspace data-handling policy governing AI model execution (`docs/architecture.md` Section 6.3).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkspaceAiPolicy {
    /// Whether non-sensitive material in this workspace may be sent to remote model providers.
    pub allow_remote_providers: bool,
    /// Whether sensitive-flagged case material may ever be sent to remote providers (default `false`).
    pub allow_sensitive_to_remote: bool,
    /// Maximum input token/character budget per request.
    pub max_input_chars: usize,
}

impl Default for WorkspaceAiPolicy {
    fn default() -> Self {
        Self {
            allow_remote_providers: false,
            allow_sensitive_to_remote: false,
            max_input_chars: 32_768,
        }
    }
}

/// Validation status of a model-generated statement citation (`docs/architecture.md` Section 6.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CitationValidationState {
    /// Generated by model; structural anchor check not yet run.
    GeneratedUnchecked,
    /// Anchor exists in the pinned input [`Document`] version (structural validity established;
    /// semantic support still requires human review).
    StructurallyValidated,
    /// Verified by a human reviewer.
    HumanReviewed,
}

/// A cited statement produced by a grounded summarization or Q&A run (`DOC-03`, `DOC-04`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CitedDraftStatement {
    /// Statement text.
    pub statement: String,
    /// Cited document version ID.
    pub document_version_id: VersionId,
    /// Cited passage anchor ID within that document version.
    pub anchor_id: OpaqueId,
    /// Validation status.
    pub validation_state: CitationValidationState,
}

/// Outcome of a grounded summarization or question-answering invocation (`DOC-03`, `DOC-04`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GroundedGenerationResult {
    /// Sufficient cited passages were found to produce a draft.
    Draft {
        /// Model and prompt template version.
        model_version: String,
        /// Statements with structural citations.
        statements: Vec<CitedDraftStatement>,
        /// Explicit list of unreadable or omitted pages not covered by the summary (`A03`).
        omitted_or_unreadable_pages: Vec<u32>,
    },
    /// Retrieved material was insufficient to answer the question without fabrication (`DOC-04`).
    InsufficientEvidence {
        /// Explanation of missing coverage.
        explanation: String,
    },
}

/// Enforces workspace data-handling policy, isolates untrusted source text as non-executable data
/// (preventing prompt-injected tool execution or permission escalation, `DOC-05`, `A03`), and
/// structurally validates all generated citations against the allowed [`Document`] versions (`D15`).
///
/// Rejects any model output that attempts to self-grant [`CitationValidationState::HumanReviewed`]
/// (`ModelError::SelfGrantedReviewStatusRejected`, `AGENTS.md` Section 5 & `docs/architecture.md` Section 6.3).
pub fn validate_and_ground_draft(
    policy: &WorkspaceAiPolicy,
    locality: &ModelLocality,
    contains_sensitive_material: bool,
    allowed_documents: &[Document],
    mut draft_statements: Vec<CitedDraftStatement>,
    model_version: impl Into<String>,
) -> Result<GroundedGenerationResult, ModelError> {
    if let ModelLocality::Remote { provider_name } = locality {
        if !policy.allow_remote_providers {
            return Err(ModelError::RemoteProviderDisallowed {
                provider: provider_name.clone(),
            });
        }
        if contains_sensitive_material && !policy.allow_sensitive_to_remote {
            return Err(ModelError::SensitiveMaterialBlockedFromRemote {
                provider: provider_name.clone(),
            });
        }
    }

    let total_chars: usize = allowed_documents
        .iter()
        .flat_map(|d| d.passages.values())
        .map(String::len)
        .sum();
    if total_chars > policy.max_input_chars {
        return Err(ModelError::InputBudgetExceeded {
            actual_chars: total_chars,
            max_chars: policy.max_input_chars,
        });
    }

    if draft_statements.is_empty() {
        return Ok(GroundedGenerationResult::InsufficientEvidence {
            explanation:
                "No supported statements could be grounded in the provided document versions."
                    .to_owned(),
        });
    }

    let mut omitted_pages = Vec::new();
    for doc in allowed_documents {
        for anchor in &doc.anchors {
            if !matches!(anchor.coverage, oia_domain::ExtractionCoverage::Complete)
                && let Some(page) = anchor.page_number
                && !omitted_pages.contains(&page)
            {
                omitted_pages.push(page);
            }
        }
    }
    omitted_pages.sort_unstable();

    for stmt in &mut draft_statements {
        // Model outputs can never self-grant `HumanReviewed` (`D15`, `docs/architecture.md` Section 6.3).
        if stmt.validation_state == CitationValidationState::HumanReviewed {
            return Err(ModelError::SelfGrantedReviewStatusRejected);
        }
        let doc = allowed_documents
            .iter()
            .find(|d| d.envelope.version_id == stmt.document_version_id)
            .ok_or_else(|| {
                ModelError::CitationToUnallowedDocument(stmt.document_version_id.clone())
            })?;
        let anchor_exists = doc.anchors.iter().any(|a| {
            a.anchor_id == stmt.anchor_id && a.document_version_id == stmt.document_version_id
        });
        if !anchor_exists {
            return Err(ModelError::NonexistentCitationAnchor {
                document_version: stmt.document_version_id.clone(),
                anchor_id: stmt.anchor_id.clone(),
            });
        }
        stmt.validation_state = CitationValidationState::StructurallyValidated;
    }

    Ok(GroundedGenerationResult::Draft {
        model_version: model_version.into(),
        statements: draft_statements,
        omitted_or_unreadable_pages: omitted_pages,
    })
}

/// Wraps untrusted document passages into a data-only prompt envelope while refusing any request
/// from document text to invoke tools or alter permissions (`DOC-05`, `A03`).
#[must_use]
pub fn isolate_untrusted_document_passage(passage_text: &str) -> DataOnlyPassageEnvelope {
    let contains_instruction_like_pattern = passage_text.contains("IGNORE PREVIOUS INSTRUCTIONS")
        || passage_text.contains("EXECUTE_TOOL")
        || passage_text.contains("GRANT_PERMISSION");
    DataOnlyPassageEnvelope {
        raw_data_text: passage_text.to_owned(),
        suspicious_directive_detected: contains_instruction_like_pattern,
        granted_tool_permissions: Vec::new(),
    }
}

/// Data-only wrapper guaranteeing that untrusted document content grants zero tool permissions (`A03`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DataOnlyPassageEnvelope {
    /// Untrusted source text treated strictly as quoted research data.
    pub raw_data_text: String,
    /// Flag indicating prompt-injection-like directives were observed in source text.
    pub suspicious_directive_detected: bool,
    /// Always empty: source documents can never grant tool permissions.
    pub granted_tool_permissions: Vec<String>,
}

/// Typed errors for `oia-models`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ModelError {
    /// Workspace policy prohibits sending data to remote AI providers.
    RemoteProviderDisallowed {
        /// Provider name.
        provider: String,
    },
    /// Sensitive case material was blocked from transmission to a remote AI provider.
    SensitiveMaterialBlockedFromRemote {
        /// Provider name.
        provider: String,
    },
    /// Input character count exceeded `WorkspaceAiPolicy::max_input_chars`.
    InputBudgetExceeded {
        /// Actual character count.
        actual_chars: usize,
        /// Configured limit.
        max_chars: usize,
    },
    /// Generated statement cited a document version outside the allowed input selection.
    CitationToUnallowedDocument(VersionId),
    /// Generated statement cited a nonexistent anchor ID (`docs/architecture.md` Section 6.3).
    NonexistentCitationAnchor {
        /// Document version ID.
        document_version: VersionId,
        /// Missing anchor ID.
        anchor_id: OpaqueId,
    },
    /// Model output attempted to claim `CitationValidationState::HumanReviewed` without human review (`D15`).
    SelfGrantedReviewStatusRejected,
}

impl fmt::Display for ModelError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::RemoteProviderDisallowed { provider } => {
                write!(
                    f,
                    "workspace policy prohibits remote AI provider '{provider}'"
                )
            }
            Self::SensitiveMaterialBlockedFromRemote { provider } => write!(
                f,
                "sensitive case material cannot be sent to remote AI provider '{provider}'"
            ),
            Self::InputBudgetExceeded {
                actual_chars,
                max_chars,
            } => write!(
                f,
                "model input length {actual_chars} exceeds budget {max_chars} chars"
            ),
            Self::CitationToUnallowedDocument(v) => {
                write!(
                    f,
                    "citation references document version '{v}' outside allowed inputs"
                )
            }
            Self::NonexistentCitationAnchor {
                document_version,
                anchor_id,
            } => write!(
                f,
                "citation anchor '{anchor_id}' does not exist in document version '{document_version}'"
            ),
            Self::SelfGrantedReviewStatusRejected => write!(
                f,
                "model output cannot self-grant CitationValidationState::HumanReviewed"
            ),
        }
    }
}

impl std::error::Error for ModelError {}
